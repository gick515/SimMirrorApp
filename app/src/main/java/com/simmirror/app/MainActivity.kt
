    private fun startCloudBridge() {
        val topic = etRoomTopic.text.toString().trim().ifEmpty { "simhub_v6_ultra" }
        ntfyEventSourceCall?.cancel()
        val req = Request.Builder().url("https://ntfy.sh/$topic/json").build()
        ntfyEventSourceCall = okHttpClient.newCall(req)
        mainScope.launch(Dispatchers.IO) {
            try {
                ntfyEventSourceCall?.execute()?.use { resp ->
                    if (resp.isSuccessful) {
                        withContext(Dispatchers.Main) { tvConnectionConsole.text = "Connected to Cloud: $topic" }
                    }
                }
            } catch (e: Exception) {
                withContext(Dispatchers.Main) { tvConnectionConsole.text = "Error: ${e.message}" }
            }
        }
    }

    private fun transmitPacket(type: String, payload: String) {
        val topic = if (::etRoomTopic.isInitialized) etRoomTopic.text.toString() else "simhub_v6_ultra"
        val json = JSONObject().put("type", type).put("payload", payload).toString()
        mainScope.launch(Dispatchers.IO) {
            try {
                val req = Request.Builder().url("https://ntfy.sh/$topic").post(json.toRequestBody("text/plain".toMediaType())).build()
                okHttpClient.newCall(req).execute().close()
            } catch (_: Exception) {}
        }
    }

    private fun executeHostDial(num: String) {
        if (num.isNotEmpty() && ActivityCompat.checkSelfPermission(this, Manifest.permission.CALL_PHONE) == PackageManager.PERMISSION_GRANTED) {
            startActivity(Intent(Intent.ACTION_CALL, Uri.parse("tel:$num")))
        }
    }

    private fun executeHostSendSms(target: String, body: String) {
        if (target.isNotEmpty() && body.isNotEmpty()) {
            val sms = SmsManager.getDefault()
            sms.sendTextMessage(target, null, body, null, null)
            tvSmsUssdResultBox.text = "SMS Sent to $target"
        }
    }

    private fun appendVaultEntry(entry: String) {
